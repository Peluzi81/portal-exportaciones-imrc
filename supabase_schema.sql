ALTER TABLE public.tracker ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.envios_facturacion ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.envios_postal ENABLE ROW LEVEL SECURITY;
