-- ============================================================================
-- ESQUEMA POSTGRESQL PARA SUPABASE — Centro de Exportación y Facturación
-- Multi-Empresa (IMRC / PPSL) · 4 Roles (admin, exportacion, consulta, facturista)
-- Ejecutar una sola vez en Supabase -> SQL Editor -> New Query -> Run
