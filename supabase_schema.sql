-- Función auxiliar para sincronizar secuencias IDENTITY luego de migrar desde SQLite
CREATE OR REPLACE FUNCTION public.sync_identity_sequences()
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    PERFORM setval(pg_get_serial_sequence('public.users', 'id'), COALESCE((SELECT MAX(id) FROM public.users), 1), (SELECT COUNT(*) > 0 FROM public.users));
    PERFORM setval(pg_get_serial_sequence('public.envios_facturacion', 'id'), COALESCE((SELECT MAX(id) FROM public.envios_facturacion), 1), (SELECT COUNT(*) > 0 FROM public.envios_facturacion));
    PERFORM setval(pg_get_serial_sequence('public.envios_postal', 'id'), COALESCE((SELECT MAX(id) FROM public.envios_postal), 1), (SELECT COUNT(*) > 0 FROM public.envios_postal));
    PERFORM setval(pg_get_serial_sequence('public.entregas_facturacion', 'id'), COALESCE((SELECT MAX(id) FROM public.entregas_facturacion), 1), (SELECT COUNT(*) > 0 FROM public.entregas_facturacion));
    PERFORM setval(pg_get_serial_sequence('public.audit_log', 'id'), COALESCE((SELECT MAX(id) FROM public.audit_log), 1), (SELECT COUNT(*) > 0 FROM public.audit_log));
END;
$$;

REVOKE ALL ON FUNCTION public.sync_identity_sequences() FROM PUBLIC;
REVOKE ALL ON FUNCTION public.sync_identity_sequences() FROM anon;
REVOKE ALL ON FUNCTION public.sync_identity_sequences() FROM authenticated;
GRANT EXECUTE ON FUNCTION public.sync_identity_sequences() TO service_role;
