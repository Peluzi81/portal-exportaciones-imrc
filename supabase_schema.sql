CREATE TABLE IF NOT EXISTS public.companies (
    id TEXT PRIMARY KEY,
    sigla TEXT NOT NULL,
    nombre TEXT NOT NULL,
    subtitulo TEXT NOT NULL DEFAULT '',
    theme_color TEXT NOT NULL DEFAULT 'teal',
    institution_json TEXT NOT NULL DEFAULT '{}',
    general_guide_json TEXT NOT NULL DEFAULT '[]',
    sort_order INTEGER NOT NULL DEFAULT 0,
    active INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT UNIQUE NOT NULL,
    full_name TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('admin', 'exportacion', 'consulta', 'facturista')),
    password_hash TEXT NOT NULL,
    active INTEGER NOT NULL DEFAULT 1,
    must_change_password INTEGER NOT NULL DEFAULT 0,
    allowed_companies TEXT NOT NULL DEFAULT '*',
    created_at TEXT NOT NULL,
    last_login TEXT
);

CREATE TABLE IF NOT EXISTS public.sessions (
    token TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    created_at TEXT NOT NULL,
    expires_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.financiadoras (
    id TEXT PRIMARY KEY,
    company_id TEXT NOT NULL DEFAULT 'imrc' REFERENCES public.companies(id) ON DELETE CASCADE,
    nombre TEXT NOT NULL,
    categoria TEXT NOT NULL,
    data_json TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    updated_by TEXT
);

CREATE TABLE IF NOT EXISTS public.favorites (
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    financiadora_id TEXT NOT NULL REFERENCES public.financiadoras(id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, financiadora_id)
);

CREATE TABLE IF NOT EXISTS public.tracker (
    period TEXT NOT NULL,
    financiadora_id TEXT NOT NULL REFERENCES public.financiadoras(id) ON DELETE CASCADE,
    amb TEXT NOT NULL DEFAULT 'pendiente',
    int TEXT NOT NULL DEFAULT 'pendiente',
    nota TEXT NOT NULL DEFAULT '',
    updated_at TEXT NOT NULL,
    updated_by TEXT,
    PRIMARY KEY (period, financiadora_id)
);

CREATE TABLE IF NOT EXISTS public.envios_facturacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id TEXT NOT NULL DEFAULT 'imrc',
    period TEXT NOT NULL,
    financiadora_id TEXT NOT NULL DEFAULT '',
    os_cod TEXT NOT NULL DEFAULT '',
    os_nombre TEXT NOT NULL,
    grupo TEXT NOT NULL DEFAULT 'directas',
    area TEXT NOT NULL CHECK (area IN ('ambulatorio', 'internado')),
    tipo TEXT NOT NULL DEFAULT 'normal',
    fecha_envio TEXT NOT NULL DEFAULT '',
    importe DOUBLE PRECISION NOT NULL DEFAULT 0,
    etiqueta TEXT NOT NULL DEFAULT '',
    observacion TEXT NOT NULL DEFAULT '',
    pdf_filename TEXT NOT NULL DEFAULT '',
    pdf_url TEXT NOT NULL DEFAULT '',
    facturas_json TEXT NOT NULL DEFAULT '[]',
    created_by TEXT NOT NULL DEFAULT '',
    updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.envios_postal (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id TEXT NOT NULL DEFAULT 'imrc',
    period TEXT NOT NULL,
    fecha_envio TEXT NOT NULL DEFAULT '',
    obra_social TEXT NOT NULL,
    medio TEXT NOT NULL DEFAULT 'ANDREANI',
    seguimiento TEXT NOT NULL DEFAULT '',
    fecha_entrega TEXT NOT NULL DEFAULT '',
    observacion TEXT NOT NULL DEFAULT '',
    created_by TEXT NOT NULL DEFAULT '',
    updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.entregas_facturacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id TEXT NOT NULL DEFAULT 'imrc',
    financiadora_id TEXT NOT NULL DEFAULT '',
    os_cod TEXT NOT NULL DEFAULT '',
    os_nombre TEXT NOT NULL,
    grupo TEXT NOT NULL DEFAULT 'directas',
    area TEXT NOT NULL CHECK (area IN ('ambulatorio', 'internado')),
    period TEXT NOT NULL,
    condicion TEXT NOT NULL DEFAULT '',
    tipo TEXT NOT NULL DEFAULT 'normal',
    importe DOUBLE PRECISION NOT NULL DEFAULT 0,
    observacion TEXT NOT NULL DEFAULT '',
    pdf_filename TEXT NOT NULL DEFAULT '',
    pdf_url TEXT NOT NULL DEFAULT '',
    facturas_json TEXT NOT NULL DEFAULT '[]',
    estado TEXT NOT NULL DEFAULT 'pendiente' CHECK (estado IN ('pendiente', 'en_proceso', 'enviado', 'observado')),
    respuesta_exportacion TEXT NOT NULL DEFAULT '',
    envio_id BIGINT,
    created_by_id BIGINT NOT NULL,
    created_by_name TEXT NOT NULL,
    created_at TEXT NOT NULL,
    processed_by TEXT NOT NULL DEFAULT '',
    processed_at TEXT NOT NULL DEFAULT '',
    updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.meta (
    key TEXT PRIMARY KEY,
    value_json TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timestamp TEXT NOT NULL,
    username TEXT NOT NULL,
    action TEXT NOT NULL,
    target TEXT NOT NULL,
    details TEXT NOT NULL,
    ip TEXT,
    company_id TEXT NOT NULL DEFAULT ''
);

-- Índices para consultas rápidas aisladas por empresa
CREATE INDEX IF NOT EXISTS idx_fin_company ON public.financiadoras(company_id);
CREATE INDEX IF NOT EXISTS idx_env_company_period ON public.envios_facturacion(company_id, period);
CREATE INDEX IF NOT EXISTS idx_pos_company_period ON public.envios_postal(company_id, period);
CREATE INDEX IF NOT EXISTS idx_entregas_company_estado ON public.entregas_facturacion(company_id, estado);
CREATE INDEX IF NOT EXISTS idx_sessions_expires ON public.sessions(expires_at);
CREATE INDEX IF NOT EXISTS idx_audit_id_desc ON public.audit_log(id DESC);

